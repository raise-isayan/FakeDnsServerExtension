    public SimpleDnsServer getDnsServer() {
        BurpExtension instance = BurpExtension.getInstance();
        if (instance != null) {
            return instance.getServer();
        } else {
            SimpleDnsServer server = new SimpleDnsServer(null);
            server.setFakeDnsOption(this.getProperty());
            return server;
        }
    }

    private void tglStartServerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tglStartServerActionPerformed
        this.setErrorMessage("");
        final FakeDnsProperty option = this.getProperty();
        final SimpleDnsServer server = this.getDnsServer();
        server.setEventHandler(new DnsHandler.MessageHandler() {

            @Override
            public void message(String message) {
                if (api() != null) {
                    api().logging().logToOutput(message);
                }
            }

            @Override
            public void catchException(Thread t, Throwable ex) {
                String message = "";
                if (ex instanceof BindException) {
                    message = "Bind Error: " + option.getBindInterface() + " - " + ex.getMessage();
                } else if (ex instanceof IOException) {
                    message = "Fatal Error: " + StringUtil.getStackTrace(ex.getMessage(), ex);
                }
                //tglStartServer.setSelected(false);
                setErrorMessage(message);
                if (api() != null) {
                    api().logging().logToError(ex.getMessage(), ex);
                }
                tglStartServer.setSelected(false);
            }

        });

        if (this.tglStartServer.isSelected()) {
            if (valid()) {
                server.setFakeDnsOption(this.getProperty());
                server.startServer();
            } else {
                this.tglStartServer.setSelected(false);
            }
        } else {
            server.stopServer();
        }
    }//GEN-LAST:event_tglStartServerActionPerformed

