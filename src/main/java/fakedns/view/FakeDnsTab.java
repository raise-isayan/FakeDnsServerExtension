    private final HostEntryItemDlg hostEntryItemDlg = new HostEntryItemDlg(null, true);

    private void showHostEntryDlg(boolean editMode) {
        try {
            this.hostEntryItemDlg.setLocationRelativeTo(this);
            if (editMode) {
                this.hostEntryItemDlg.setPropery(this.getEditItem());
            } else {
                HostNameItem item = new HostNameItem(true,"");
                this.hostEntryItemDlg.setPropery(item);
            }

            this.hostEntryItemDlg.setVisible(true);
            if (this.hostEntryItemDlg.getModalResult() == JOptionPane.OK_OPTION) {
                HostNameItem editItem = this.hostEntryItemDlg.getPropery();
                this.setEditItem(editItem, editMode);
            }
        } catch (Exception ex) {
            logger.log(Level.SEVERE, ex.getMessage(), ex);
        }
    }

    private final MultiItemDlg multiItemDlg = new MultiItemDlg(null, true);

    private void showMultiLineDlg() {
        try {
            this.multiItemDlg.setLocationRelativeTo(this);
            this.multiItemDlg.setMultiLine(new String[]{""});
            this.multiItemDlg.setVisible(true);
            if (this.multiItemDlg.getModalResult() == JOptionPane.OK_OPTION) {
                String[] lines = this.multiItemDlg.getMultiLine();
                for (String line : lines) {
                    HostNameItem item = new HostNameItem();
                    item.setEnable(true);
                    item.setHostName(line);
                    this.setEditItem(item, false);
                }
            }
        } catch (Exception ex) {
            logger.log(Level.SEVERE, ex.getMessage(), ex);
        }
    }

    private void setEditItem(HostNameItem item, boolean update) {
        Object[] rows = HostNameItem.toObjects(item);
        SwingUtil.addOrUpdateItem(this.tblFakeDomains, rows, update);
    }

    private void removeDomainItem() {
        SwingUtil.removeItem(this.tblFakeDomains);
    }

    private void removeAllDomainItem() {
        SwingUtil.removeAllItem(this.tblFakeDomains);
    }

    private HostNameItem getEditItem() {
        HostNameItem item = new HostNameItem();
        Object editCols[] = SwingUtil.editItem(this.tblFakeDomains);
        if (editCols != null) {
            item = HostNameItem.fromObjects(editCols);
        }
        return item;
    }

    public List<HostNameItem> getFakeDomains() {
        javax.swing.JTable srcTable = this.tblFakeDomains;
        List<HostNameItem> list = new ArrayList<>();
        for (int i = 0; i < srcTable.getRowCount(); i++) {
            Object editRows[] = this.modelFakeDomains.getRows(i);
            list.add(HostNameItem.fromObjects(editRows));
        }
        return list;
    }

    public void setFakeDomains(List<HostNameItem> list) {
        this.modelFakeDomains.removeAll();
        for (int i = 0; i < list.size(); i++) {
            HostNameItem bean = list.get(i);
            Object editRows[] = HostNameItem.toObjects(bean);
            this.modelFakeDomains.addRow(editRows);
        }
    }

    private List<HostNameItem> getNameServers() {
        final List<HostNameItem> list = HostNameItem.parseHostList(this.txtFakeServers.getText());
        return list;
    }

    public boolean valid() {
        FakeDnsProperty fakeDnsOption = this.getProperty();
        if (!IpUtil.isIPv4Address(fakeDnsOption.getBindInterface())) {
            this.setErrorMessage("interface ipv4 format error:" + fakeDnsOption.getBindInterface());
            return false;
        }
        if (!IpUtil.isIPv4Address(fakeDnsOption.getFakeIP())) {
            this.setErrorMessage("fakeip ipv4 format error:" + fakeDnsOption.getFakeIP());
            return false;
        }
        return true;
    }

    public void setErrorMessage(String message) {
        this.lblExceptionMessage.setText(message);
    }


